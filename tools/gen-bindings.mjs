// gen-bindings.mjs — 从 kb/ossie SQLite 生成：
//   1) packages/ontology/src/kb/beadCatalog.ts（引擎绑定，含 ttl 导出同源）
//   2) kb/bead-catalog.ttl（可选 OWL 导出，非权威）
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readBeadRows, DB_PATH } from './ossie-lib.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const ROOT = join(here, '..')
const KB_TS = join(ROOT, 'packages', 'ontology', 'src', 'kb')
mkdirSync(KB_TS, { recursive: true })
const BEAD_TS = join(KB_TS, 'beadCatalog.ts')
const TTL = join(ROOT, 'kb', 'bead-catalog.ttl')

const rows = readBeadRows()
const esc = (s) => JSON.stringify(String(s))
const w = (lines) => lines.join('\n') + '\n'

function beadTS(rowsArr) {
  return [
    '// GENERATED by tools/gen-bindings.mjs from kb/ossie (Apache Ossie standard: ontology.yaml + semantic_model.yaml + data/*.sql) — do not edit.',
    '// BaziDIY 珠子库绑定（只读；实例源=SQLite）。',
    'export interface BeadRow { id: string; bead_id: string; name: string; wuxing: string; variant: string; diameters: number[]; color: string; image: string; image_w: number; image_h: number }',
    'export const beads: BeadRow[] = ' + JSON.stringify(rowsArr, null, 2),
    '',
  ].join('\n')
}

function beadTTL(rowsArr) {
  const materials = []
  const seen = new Set()
  for (const b of rowsArr) {
    if (!seen.has(b.bead_id)) { seen.add(b.bead_id); materials.push({ slug: b.bead_id, name: b.name }) }
  }
  const variants = [...new Set(rowsArr.map((b) => b.variant))]
  const diaSet = [...new Set(rowsArr.flatMap((b) => b.diameters))].sort((a, b) => a - b)
  const L = ['@prefix bzd: <https://bazidiy.example/ontology#> .', '',
    '# 珠子库 ttl = 由 kb/ossie(SQLite) 导出的 OWL 视图（非权威；权威见 kb/ossie/ontology+semantic_model+data）', '',
    'bzd:BeadCatalogOntology a owl:Ontology .', '',
    'bzd:Bead a owl:Class .', 'bzd:BeadVariant a owl:Class .', 'bzd:BeadMaterial a owl:Class .', 'bzd:globalDiameterDomain a owl:Class .',
    'bzd:hasVariant a owl:ObjectProperty .', 'bzd:hasVariant a owl:FunctionalProperty .',
    'bzd:belongsToElement a owl:ObjectProperty .', 'bzd:belongsToElement a owl:FunctionalProperty .',
    'bzd:materialOf a owl:ObjectProperty .', 'bzd:materialOf a owl:FunctionalProperty .',
    'bzd:hasDiameter a owl:DatatypeProperty .', 'bzd:hasColor a owl:DatatypeProperty .', 'bzd:hasImage a owl:DatatypeProperty .',
    'bzd:hasImageW a owl:DatatypeProperty .', 'bzd:hasImageH a owl:DatatypeProperty .', 'bzd:label a owl:DatatypeProperty .',
    'bzd:contains a owl:DatatypeProperty .', '']
  for (const v of variants) L.push(`bzd:${v} a bzd:BeadVariant .`)
  L.push('')
  for (const m of materials) { L.push(`bzd:mat_${m.slug} a bzd:BeadMaterial .`); L.push(`bzd:mat_${m.slug} bzd:label ${esc(m.name)} .`) }
  L.push('')
  for (const b of rowsArr) {
    const id = b.id
    L.push(`bzd:${id} a bzd:Bead .`)
    L.push(`bzd:${id} bzd:label ${esc(b.name)} .`)
    L.push(`bzd:${id} bzd:hasVariant bzd:${b.variant} .`)
    L.push(`bzd:${id} bzd:belongsToElement bzd:${b.wuxing} .`)
    L.push(`bzd:${id} bzd:materialOf bzd:mat_${b.bead_id} .`)
    for (const d of b.diameters) L.push(`bzd:${id} bzd:hasDiameter ${d} .`)
    L.push(`bzd:${id} bzd:hasColor ${esc(b.color)} .`)
    L.push(`bzd:${id} bzd:hasImage ${esc(b.image)} .`)
    L.push(`bzd:${id} bzd:hasImageW ${b.image_w} .`)
    L.push(`bzd:${id} bzd:hasImageH ${b.image_h} .`)
  }
  L.push('')
  for (const d of diaSet) L.push(`bzd:globalDiameterDomain bzd:contains ${d} .`)
  return w(L)
}

// 与现绑定对拍（写入前比较）
let prev = null
try {
  prev = (await import('file:///' + BEAD_TS.replace(/\\/g, '/'))).beads
} catch { /* first run */ }
const same = prev ? JSON.stringify(prev.map((x) => ({ ...x }))) === JSON.stringify(rows) : null

writeFileSync(BEAD_TS, beadTS(rows), 'utf8')
writeFileSync(TTL, beadTTL(rows), 'utf8')
console.log('bindings written: beadCatalog.ts (' + rows.length + ' rows) + kb/bead-catalog.ttl (export)')
console.log('parity vs previous binding:', same === null ? 'n/a(first run)' : (same ? 'EQUAL' : 'DIFF'))
