// export-ossie-style.mjs — 把当前款式绑定导出为 style_seed.sql（一次性/可重生成）。
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, '..', 'kb', 'ossie', 'data')
mkdirSync(OUT, { recursive: true })
const styles = (await import('file:///' + join(here, '..', 'packages', 'ontology', 'src', 'kb', 'styleLibrary.ts').replace(/\\/g, '/'))).styles
const q = (v) => (v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'")
const lines = ['-- GENERATED by tools/export-ossie-style.mjs — 款式种子。', '']
for (const [id, cfg] of Object.entries(styles.styles)) {
  lines.push(`INSERT OR REPLACE INTO styles(id, name) VALUES (${q(id)}, ${q(cfg.name)});`)
  for (const p of cfg.positions) {
    lines.push(`INSERT OR REPLACE INTO slots(style_id, slot, role, min_dia, max_dia, allowed_variants) VALUES (${q(id)}, ${p.slot}, ${q(p.role)}, ${p.min_dia ?? 'NULL'}, ${p.max_dia ?? 'NULL'}, ${q(JSON.stringify(p.variant_filter ?? []))});`)
  }
  for (const c of cfg.constraints) {
    lines.push(`INSERT OR REPLACE INTO style_constraints(style_id, name, type, variables, params, reason) VALUES (${q(id)}, ${q(c.name)}, ${q(c.type)}, ${q(JSON.stringify(c.variables))}, ${c.params ? q(JSON.stringify(c.params)) : 'NULL'}, ${q(c.reason ?? '')});`)
  }
}
for (const [bd, sd] of Object.entries(styles.spacer_diameter_map)) {
  lines.push(`INSERT OR REPLACE INTO spacer_map(body, spacer) VALUES (${bd}, ${sd});`)
}
writeFileSync(join(OUT, 'style_seed.sql'), lines.join('\n') + '\n', 'utf8')
console.log('style seed written: styles=' + Object.keys(styles.styles).length)
