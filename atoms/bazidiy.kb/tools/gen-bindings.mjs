// gen-bindings.mjs — 从 kb/ossie SQLite 生成引擎绑定 + OWL 导出：
//   bead:   packages/ontology/src/kb/beadCatalog.ts + kb/bead-catalog.ttl
//   wuxing: packages/ontology/src/kb/vocab.ts        + kb/wuxing-ganzhi.ttl
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DatabaseSync } from 'node:sqlite'
import { DATA_DIR, DB_PATH, readBeadRows } from './ossie-lib.mjs'
import { readFileSync } from 'node:fs'

const here = dirname(fileURLToPath(import.meta.url))
const ROOT = join(here, '..')
const KB_TS = join(ROOT, 'impl') // 绑定真源夹（顶层原子文件夹）；由 tools/sync-atoms.mjs 镜像进 src/_atoms
mkdirSync(KB_TS, { recursive: true })

const esc = (s) => JSON.stringify(String(s))
const w = (lines) => lines.join('\n') + '\n'

const db = new DatabaseSync(DB_PATH)
for (const [schema, seed] of [['bead_schema.sql', 'bead_seed.sql'], ['wuxing_schema.sql', 'wuxing_seed.sql']]) {
  db.exec(readFileSync(join(DATA_DIR, schema), 'utf8'))
  db.exec(readFileSync(join(DATA_DIR, seed), 'utf8'))
}
const q = (sql) => db.prepare(sql).all()

// ===================== bead =====================
const beadRows = readBeadRows()
const beadTS = (rowsArr) => [
  '// GENERATED by tools/gen-bindings.mjs from kb/ossie (Apache Ossie standard: ontology.yaml + semantic_model.yaml + data/*.sql) — do not edit.',
  '// BaziDIY 珠子库绑定（只读；实例源=SQLite）。',
  'export interface BeadRow { id: string; bead_id: string; name: string; wuxing: string; variant: string; diameters: number[]; color: string; image: string; image_w: number; image_h: number }',
  'export const beads: BeadRow[] = ' + JSON.stringify(rowsArr, null, 2),
  '',
].join('\n')
function beadTTL(rowsArr) {
  const materials = []; const seen = new Set()
  for (const b of rowsArr) { if (!seen.has(b.bead_id)) { seen.add(b.bead_id); materials.push({ slug: b.bead_id, name: b.name }) } }
  const variants = [...new Set(rowsArr.map((b) => b.variant))]
  const diaSet = [...new Set(rowsArr.flatMap((b) => b.diameters))].sort((a, b) => a - b)
  const L = ['@prefix bzd: <https://bazidiy.example/ontology#> .', '', '# 珠子库 ttl = 由 kb/ossie(SQLite) 导出的 OWL 视图（非权威）', '',
    'bzd:BeadCatalogOntology a owl:Ontology .', '',
    'bzd:Bead a owl:Class .', 'bzd:BeadVariant a owl:Class .', 'bzd:BeadMaterial a owl:Class .', 'bzd:globalDiameterDomain a owl:Class .',
    'bzd:hasVariant a owl:ObjectProperty .', 'bzd:hasVariant a owl:FunctionalProperty .',
    'bzd:belongsToElement a owl:ObjectProperty .', 'bzd:belongsToElement a owl:FunctionalProperty .',
    'bzd:materialOf a owl:ObjectProperty .', 'bzd:materialOf a owl:FunctionalProperty .',
    'bzd:hasDiameter a owl:DatatypeProperty .', 'bzd:hasColor a owl:DatatypeProperty .', 'bzd:hasImage a owl:DatatypeProperty .',
    'bzd:hasImageW a owl:DatatypeProperty .', 'bzd:hasImageH a owl:DatatypeProperty .', 'bzd:label a owl:DatatypeProperty .', 'bzd:contains a owl:DatatypeProperty .', '']
  for (const v of variants) L.push(`bzd:${v} a bzd:BeadVariant .`)
  L.push('')
  for (const m of materials) { L.push(`bzd:mat_${m.slug} a bzd:BeadMaterial .`); L.push(`bzd:mat_${m.slug} bzd:label ${esc(m.name)} .`) }
  L.push('')
  for (const b of rowsArr) {
    const id = b.id
    L.push(`bzd:${id} a bzd:Bead .`)
    L.push(`bzd:${id} bzd:label ${esc(b.name)} .`)
    L.push(`bzd:${id} bzd:hasVariant bzd:${b.variant} .`)
    L.push(`bzd:${id} bzd:belongsToElement bzd:${b.wuxing} .`)
    L.push(`bzd:${id} bzd:materialOf bzd:mat_${b.bead_id} .`)
    for (const d of b.diameters) L.push(`bzd:${id} bzd:hasDiameter ${d} .`)
    L.push(`bzd:${id} bzd:hasColor ${esc(b.color)} .`)
    L.push(`bzd:${id} bzd:hasImage ${esc(b.image)} .`)
    L.push(`bzd:${id} bzd:hasImageW ${b.image_w} .`)
    L.push(`bzd:${id} bzd:hasImageH ${b.image_h} .`)
  }
  L.push('')
  for (const d of diaSet) L.push(`bzd:globalDiameterDomain bzd:contains ${d} .`)
  return w(L)
}

// ===================== wuxing =====================
const elements = q('SELECT name, generates, restricts FROM elements ORDER BY rowid')
const stems = q('SELECT name, ord, element FROM stems ORDER BY ord')
const branches = q('SELECT name, ord, element FROM branches ORDER BY ord')
const seasons = q('SELECT name, month, day FROM seasons ORDER BY rowid')
const elementOrder = elements.map((e) => e.name)
const generates = Object.fromEntries(elements.map((e) => [e.name, e.generates]))
const restricts = Object.fromEntries(elements.map((e) => [e.name, e.restricts]))

const vocabTS = () => [
  '// GENERATED by tools/gen-bindings.mjs from kb/ossie (Apache Ossie standard) — do not edit.',
  '// BaziDIY 五行·干支·节气 词库绑定（只读；实例源=SQLite）。',
  'export const elementOrder: string[] = ' + JSON.stringify(elementOrder),
  'export const generates: Record<string, string> = ' + JSON.stringify(generates),
  'export const restricts: Record<string, string> = ' + JSON.stringify(restricts),
  'export interface Stem { name: string; order: number; element: string }',
  'export interface Branch { name: string; order: number; element: string }',
  'export interface SeasonNode { name: string; month: number; day: number }',
  'export const stems: Stem[] = ' + JSON.stringify(stems.map((s) => ({ name: s.name, order: s.ord, element: s.element }))),
  'export const branches: Branch[] = ' + JSON.stringify(branches.map((b) => ({ name: b.name, order: b.ord, element: b.element }))),
  'export const seasons: SeasonNode[] = ' + JSON.stringify(seasons.map((s) => ({ name: s.name, month: s.month, day: s.day }))),
  'export const STEM_NAMES: string[] = ' + JSON.stringify(stems.map((s) => s.name)),
  'export const BRANCH_NAMES: string[] = ' + JSON.stringify(branches.map((b) => b.name)),
  'export const STEM_ELEMENT: Record<string, string> = ' + JSON.stringify(Object.fromEntries(stems.map((s) => [s.name, s.element]))),
  'export const BRANCH_ELEMENT: Record<string, string> = ' + JSON.stringify(Object.fromEntries(branches.map((b) => [b.name, b.element]))),
  '',
].join('\n')

const wuxingTTL = () => {
  const L = ['@prefix bzd: <https://bazidiy.example/ontology#> .', '', '# 五行/干支/节气 ttl = 由 kb/ossie(SQLite) 导出的 OWL 视图（非权威）', '',
    'bzd:WuxingGanzhiOntology a owl:Ontology .', '',
    'bzd:WuxingElement a owl:Class .', 'bzd:HeavenlyStem a owl:Class .', 'bzd:EarthlyBranch a owl:Class .', 'bzd:SeasonNode a owl:Class .',
    'bzd:generates a owl:ObjectProperty .', 'bzd:restricts a owl:ObjectProperty .', 'bzd:belongsToElement a owl:ObjectProperty .',
    'bzd:order a owl:DatatypeProperty .', 'bzd:month a owl:DatatypeProperty .', 'bzd:day a owl:DatatypeProperty .', '']
  for (const e of elements) {
    L.push(`bzd:${e.name} a bzd:WuxingElement .`)
    L.push(`bzd:${e.name} bzd:generates bzd:${e.generates} .`)
    L.push(`bzd:${e.name} bzd:restricts bzd:${e.restricts} .`)
  }
  L.push('')
  for (const s of stems) { L.push(`bzd:${s.name} a bzd:HeavenlyStem .`); L.push(`bzd:${s.name} bzd:order ${s.ord} .`); L.push(`bzd:${s.name} bzd:belongsToElement bzd:${s.element} .`) }
  L.push('')
  for (const b of branches) { L.push(`bzd:${b.name} a bzd:EarthlyBranch .`); L.push(`bzd:${b.name} bzd:order ${b.ord} .`); L.push(`bzd:${b.name} bzd:belongsToElement bzd:${b.element} .`) }
  L.push('')
  for (const s of seasons) { L.push(`bzd:${s.name} a bzd:SeasonNode .`); L.push(`bzd:${s.name} bzd:month ${s.month} .`); L.push(`bzd:${s.name} bzd:day ${s.day} .`) }
  return w(L)
}

writeFileSync(join(KB_TS, 'beadCatalog.ts'), beadTS(beadRows), 'utf8')
writeFileSync(join(ROOT, 'kb', 'bead-catalog.ttl'), beadTTL(beadRows), 'utf8')
writeFileSync(join(KB_TS, 'vocab.ts'), vocabTS(), 'utf8')
writeFileSync(join(ROOT, 'kb', 'wuxing-ganzhi.ttl'), wuxingTTL(), 'utf8')

// ===================== style =====================
const styleIds = q('SELECT id, name FROM styles ORDER BY rowid')
const slotRows = q('SELECT style_id, slot, role, min_dia, max_dia, allowed_variants FROM slots ORDER BY rowid')
const consRows = q('SELECT style_id, name, type, variables, params, reason FROM style_constraints ORDER BY rowid')
const spacerRows = q('SELECT body, spacer FROM spacer_map ORDER BY body')
const positionsOf = (id) => slotRows.filter((s) => s.style_id === id).map((s) => {
  const p = { slot: s.slot, role: s.role }
  if (s.min_dia !== null) p.min_dia = s.min_dia
  if (s.max_dia !== null) p.max_dia = s.max_dia
  p.variant_filter = JSON.parse(s.allowed_variants)
  return p
})
const constraintsOf = (id) => consRows.filter((c) => c.style_id === id).map((c) => {
  const out = { name: c.name, type: c.type, variables: JSON.parse(c.variables) }
  if (c.params !== null) out.params = JSON.parse(c.params)
  if (c.reason) out.reason = c.reason
  return out
})
const stylesObj = {}
for (const s of styleIds) stylesObj[s.id] = { name: s.name, positions: positionsOf(s.id), constraints: constraintsOf(s.id) }
const spacerMap = {}
for (const r of spacerRows) spacerMap[String(r.body)] = r.spacer
const styleLibRaw = { styles: stylesObj, spacer_diameter_map: spacerMap }
const styleLibTS = () => [
  '// GENERATED by tools/gen-bindings.mjs from kb/ossie (Apache Ossie standard) — do not edit.',
  '// BaziDIY 款式库绑定（只读；实例源=SQLite）。',
  'export const styles: Record<string, unknown> = ' + JSON.stringify(styleLibRaw, null, 2),
  '',
].join('\n')
const styleTTL = () => {
  const L = ['@prefix bzd: <https://bazidiy.example/ontology#> .', '', '# 款式 ttl = 由 kb/ossie(SQLite) 导出的 OWL 视图（非权威）', '',
    'bzd:StyleLibraryOntology a owl:Ontology .', '', 'bzd:Style a owl:Class .', 'bzd:config a owl:DatatypeProperty .', '']
  for (const [id, cfg] of Object.entries(stylesObj)) {
    L.push(`bzd:${id} a bzd:Style .`)
    L.push(`bzd:${id} bzd:config ${esc(JSON.stringify({ name: cfg.name, positions: cfg.positions, constraints: cfg.constraints }))} .`)
    L.push('')
  }
  L.push('bzd:spacerMap a owl:Class .')
  for (const r of spacerRows) {
    L.push(`bzd:spacerMap${r.body} a bzd:spacerMap .`)
    L.push(`bzd:spacerMap${r.body} bzd:body ${r.body} .`)
    L.push(`bzd:spacerMap${r.body} bzd:spacer ${r.spacer} .`)
  }
  return w(L)
}
writeFileSync(join(KB_TS, 'styleLibrary.ts'), styleLibTS(), 'utf8')
writeFileSync(join(ROOT, 'kb', 'style-library.ttl'), styleTTL(), 'utf8')
db.close()
console.log('bindings written: beadCatalog.ts (' + beadRows.length + '), vocab.ts (' + stems.length + '/' + branches.length + '), styleLibrary.ts (' + styleIds.length + ') + ttl exports')
