// export-ossie-seed.mjs — 一次性把当前珠子绑定导出为 Ossie 数据种子(SQLite schema+seed)。
// 输出：atoms/bazidiy.kb/kb/ossie/data/bead_schema.sql + bead_seed.sql
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, '..', 'kb', 'ossie', 'data')
mkdirSync(OUT, { recursive: true })

const beads = (await import('file:///' + join(here, '..', 'impl', 'beadCatalog.ts').replace(/\\/g, '/'))).beads

const esc = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const q = (v) => (v === null || v === undefined ? 'NULL' : esc(v))

const materials = []
const seen = new Set()
for (const b of beads) {
  if (!seen.has(b.bead_id)) { seen.add(b.bead_id); materials.push({ id: b.bead_id, name: b.name }) }
}
const variants = [...new Set(beads.map((b) => b.variant))]

const schema = [
  '-- GENERATED by tools/export-ossie-seed.mjs from kb binding (parity source).',
  '-- BaziDIY 珠子库 · Ossie 数据层 schema（实例 = 本库；契约见 ../*.yaml）',
  'PRAGMA foreign_keys = ON;',
  '',
  'CREATE TABLE IF NOT EXISTS materials (',
  '  id   TEXT PRIMARY KEY,          -- 材料键（唯一）',
  '  name TEXT NOT NULL              -- 材料名（如 白银）',
  ');',
  '',
  'CREATE TABLE IF NOT EXISTS variants (',
  '  id   TEXT PRIMARY KEY           -- 变体（round/buddha/barrel/spacer/pixiu）',
  ');',
  '',
  'CREATE TABLE IF NOT EXISTS beads (',
  '  id        TEXT PRIMARY KEY,     -- 珠实例唯一标识（材料×变体）',
  '  bead_id   TEXT NOT NULL,        -- 材料键（=materials.id）',
  '  material  TEXT NOT NULL REFERENCES materials(id),',
  '  variant   TEXT NOT NULL REFERENCES variants(id),',
  '  name      TEXT NOT NULL,        -- 展示名（如 南红）',
  '  wuxing    TEXT NOT NULL,        -- 属五行：木/火/土/金/水',
  '  diameters TEXT NOT NULL,        -- JSON 数组，如 [6,8,10,12]',
  '  color     TEXT NOT NULL,        -- 主题色 #RRGGBB',
  '  image     TEXT NOT NULL,        -- 图片地址（相对 /beads）',
  '  image_w   INTEGER NOT NULL,',
  '  image_h   INTEGER NOT NULL',
  ');',
  '',
  'CREATE INDEX IF NOT EXISTS idx_beads_material ON beads(material);',
  'CREATE INDEX IF NOT EXISTS idx_beads_wuxing  ON beads(wuxing);',
  '',
].join('\n')

const seed = ['-- GENERATED by tools/export-ossie-seed.mjs — 33 珠 / ' + materials.length + ' 珠料 / ' + variants.length + ' 变体。', '']
for (const m of materials) seed.push(`INSERT OR REPLACE INTO materials(id, name) VALUES (${q(m.id)}, ${q(m.name)});`)
seed.push('')
for (const v of variants) seed.push(`INSERT OR REPLACE INTO variants(id) VALUES (${q(v)});`)
seed.push('')
for (const b of beads) {
  seed.push(`INSERT OR REPLACE INTO beads(id, bead_id, material, variant, name, wuxing, diameters, color, image, image_w, image_h) VALUES (` +
    [q(b.id), q(b.bead_id), q(b.bead_id), q(b.variant), q(b.name), q(b.wuxing), q(JSON.stringify(b.diameters)), q(b.color), q(b.image), b.image_w, b.image_h].join(', ') + `);`)
}

writeFileSync(join(OUT, 'bead_schema.sql'), schema, 'utf8')
writeFileSync(join(OUT, 'bead_seed.sql'), seed.join('\n') + '\n', 'utf8')
console.log('seed written:', beads.length, 'beads /', materials.length, 'materials /', variants.length, 'variants')
